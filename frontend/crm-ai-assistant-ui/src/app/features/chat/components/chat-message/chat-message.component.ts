import { Component, EventEmitter, Input, OnChanges, Output, SimpleChanges } from '@angular/core';
import { ChatUiMessage, ClarificationSuggestion } from '../../../../core/models/chat-response.model';
import {
  extractRows,
  isCountResult,
  shouldShowTable
} from '../../../../core/services/crm-table.util';

@Component({
  selector: 'app-chat-message',
  templateUrl: './chat-message.component.html',
  styleUrl: './chat-message.component.scss',
  standalone: false
})
export class ChatMessageComponent implements OnChanges {
  /** Fixed frontend-controlled clarification option (never generated by the model). */
  readonly otherOptionLabel = 'Other — Let me specify';

  @Input({ required: true }) message!: ChatUiMessage;
  @Input() suggestionsDisabled = false;
  @Output() readonly suggestionSelected = new EventEmitter<string>();

  mode: 'plain' | 'count' | 'table' | 'clarification' = 'plain';
  countLabel = 'Count';
  countCapped = '';
  limitationNotice = '';
  userTextDir: 'auto' | 'ltr' = 'ltr';

  showCustomClarification = false;
  customClarificationText = '';
  customSubmitting = false;

  ngOnChanges(changes: SimpleChanges): void {
    if (changes['message']) {
      this.showCustomClarification = false;
      this.customClarificationText = '';
      this.customSubmitting = false;
      this.rebuild();
    }
    if (changes['suggestionsDisabled'] && !this.suggestionsDisabled) {
      this.customSubmitting = false;
    }
  }

  get canSubmitCustomClarification(): boolean {
    return (
      !this.suggestionsDisabled &&
      !this.customSubmitting &&
      this.customClarificationText.trim().length > 0
    );
  }

  onSuggestionClick(suggestion: ClarificationSuggestion): void {
    const question = (suggestion.question || '').trim();
    if (!question || this.suggestionsDisabled || this.customSubmitting) {
      return;
    }
    this.showCustomClarification = false;
    this.suggestionSelected.emit(question);
  }

  onOtherClick(): void {
    if (this.suggestionsDisabled || this.customSubmitting) {
      return;
    }
    this.showCustomClarification = !this.showCustomClarification;
    if (!this.showCustomClarification) {
      this.customClarificationText = '';
    }
  }

  onCustomClarificationSubmit(): void {
    const text = this.customClarificationText.trim();
    if (!text || this.suggestionsDisabled || this.customSubmitting) {
      return;
    }
    this.customSubmitting = true;
    this.suggestionSelected.emit(text);
  }

  private rebuild(): void {
    const msg = this.message;
    if (!msg) {
      return;
    }

    this.userTextDir = /[\u0600-\u06FF]/.test(msg.text || '') ? 'auto' : 'ltr';

    if (msg.role === 'user' || msg.role === 'meta' || msg.error) {
      this.mode = 'plain';
      return;
    }

    // Clarification UI even when AI chips were all filtered out (custom reply only).
    if (msg.responseType === 'clarification') {
      this.mode = 'clarification';
      return;
    }

    if (!msg.structuredData) {
      this.mode = 'plain';
      return;
    }

    const structured = msg.structuredData;
    const rows = extractRows(structured);
    this.limitationNotice = this.buildLimitationNotice(structured);

    if (isCountResult(structured, rows) && structured.count != null) {
      this.mode = 'count';
      this.countLabel = 'Count';
      this.countCapped = structured.countMayBeCapped
        ? ' (at least — may be higher)'
        : '';
      return;
    }

    if (shouldShowTable(structured, rows)) {
      this.mode = 'table';
      return;
    }

    this.mode = 'plain';
  }

  private buildLimitationNotice(structured: NonNullable<ChatUiMessage['structuredData']>): string {
    const mode = String(structured.resultMode || '').toLowerCase();
    const limitation = (structured.limitation || '').trim();
    if (mode !== 'partial' || !limitation) {
      return '';
    }
    return `The CRM data is displayed above. ${limitation}`;
  }
}
